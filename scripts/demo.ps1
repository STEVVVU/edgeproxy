# Runs the end-to-end edgeproxy demo topology as plain local processes: N
# upstream fixtures behind one proxy, with the metrics endpoint exposed for a
# local Prometheus to scrape.
#
# Every process is a child of this script and is terminated on exit, so the demo
# leaves nothing running.
#
#   .\scripts\demo.ps1                      # 2 upstreams, plaintext only
#   .\scripts\demo.ps1 -Upstreams 3 -Tls    # 3 upstreams, plus an HTTPS listener
#
# Then, from another shell:
#
#   curl http://127.0.0.1:8080/             # proxied, round robin over upstreams
#   curl -k https://127.0.0.1:8443/         # same, TLS-terminated (-k: self-signed)
#   curl http://127.0.0.1:9090/metrics      # edgeproxy Prometheus metrics
#
# Repeated calls to `/` return `upstream=a`, `upstream=b`, ... in rotation, which
# is the visible evidence of load balancing. Killing one fixture and continuing to
# curl shows the health check ejecting it and the remaining upstreams absorbing
# the traffic.
param(
    # Number of upstream fixtures to run. Each listens on 127.0.0.1:19001+n and
    # is identified by a letter in its response body.
    [ValidateRange(1, 26)]
    [int]$Upstreams = 2,

    # Also serve an HTTPS listener on 127.0.0.1:8443. Requires openssl on PATH; a
    # throwaway certificate is generated into demo/tls/ if absent.
    [switch]$Tls
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
. (Join-Path $PSScriptRoot "TestCertificate.ps1")

# Writes the generated config as UTF-8 with no byte-order mark. Windows
# PowerShell's `Set-Content -Encoding utf8` prepends a BOM; the TOML parser
# tolerates it, but a BOM in a generated config is still noise nobody expects.
function Set-ConfigFile {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true, ValueFromPipeline = $true)][string]$Content
    )

    process {
        $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
        $resolved = Join-Path (Get-Location).Path $Path
        [System.IO.File]::WriteAllText($resolved, $Content, $utf8NoBom)
    }
}

$processes = @()
$listen = "127.0.0.1:8080"
$tlsListen = "127.0.0.1:8443"
$metricsListen = "127.0.0.1:9090"
$firstUpstreamPort = 19001

Push-Location $root
try {
    cargo build --release --bins --examples
    if ($LASTEXITCODE -ne 0) {
        throw "cargo build failed with exit code $LASTEXITCODE"
    }
    New-Item -ItemType Directory -Force -Path "demo" | Out-Null

    # The config is generated rather than committed because -Upstreams is
    # variable and `upstreams[].address` is a SocketAddr: edgeproxy performs no
    # DNS resolution, so each fixture's port has to be written out literally.
    $upstreamSections = New-Object System.Collections.Generic.List[string]
    for ($index = 0; $index -lt $Upstreams; $index++) {
        $id = [char]([int][char]'a' + $index)
        $port = $firstUpstreamPort + $index
        $upstreamSections.Add(@"

[[upstreams]]
name = "fixture-$id"
address = "127.0.0.1:$port"
health_path = "/health"

"@)
    }

    $tlsSection = ""
    if ($Tls) {
        New-TestCertificate -Directory (Join-Path $root "demo/tls")
        $tlsSection = @"

[tls]
listen = "$tlsListen"
certificate = "demo/tls/test-only-localhost.crt"
private_key = "demo/tls/test-only-localhost.key"

"@
    }

    $configuration = "demo/edgeproxy.demo.toml"
    @"
# Generated by scripts/demo.ps1 -Upstreams $Upstreams. Edits are overwritten on
# the next run; change the script instead.

listen = "$listen"
metrics_listen = "$metricsListen"
policy = "round_robin"
max_in_flight = 1024
shutdown_grace_ms = 5000
preserve_host = false
$tlsSection
[limits]
max_header_bytes = 16384
max_headers = 64
max_request_line_bytes = 8192
max_body_bytes = 1048576
max_response_header_bytes = 32768

[timeouts]
request_header_ms = 5000
request_body_ms = 10000
connect_ms = 500
upstream_write_ms = 5000
upstream_response_header_ms = 5000
upstream_idle_ms = 15000
downstream_write_ms = 15000

[retries]
max_attempts = 2
retry_statuses = [502, 503, 504]

[circuit_breaker]
failure_threshold = 5
open_ms = 10000

# The fixture upstream answers any path with a fixed body, so /health works.
[health_check]
interval_ms = 2000
timeout_ms = 500
unhealthy_threshold = 2
healthy_threshold = 2
$($upstreamSections -join "")
"@ | Set-ConfigFile -Path $configuration

    for ($index = 0; $index -lt $Upstreams; $index++) {
        $id = [char]([int][char]'a' + $index)
        $port = $firstUpstreamPort + $index
        $fixture = Start-Process `
            -FilePath "target/release/examples/fixture_upstream.exe" `
            -ArgumentList "--listen", "127.0.0.1:$port", "--id", "$id" `
            -RedirectStandardOutput "demo/fixture-$id.log" `
            -RedirectStandardError "demo/fixture-$id.err.log" `
            -WindowStyle Hidden `
            -PassThru
        $processes += $fixture
        Write-Host "upstream fixture-$id -> 127.0.0.1:$port (pid $($fixture.Id))"
    }

    $proxy = Start-Process `
        -FilePath "target/release/edgeproxy.exe" `
        -ArgumentList "--config", $configuration `
        -RedirectStandardOutput "demo/edgeproxy.log" `
        -RedirectStandardError "demo/edgeproxy.err.log" `
        -WindowStyle Hidden `
        -PassThru
    $processes += $proxy

    Start-Sleep -Seconds 2
    if ($proxy.HasExited) {
        Write-Host "`nedgeproxy exited immediately. Stderr:"
        Get-Content "demo/edgeproxy.err.log" -ErrorAction SilentlyContinue |
            Write-Host
        throw "edgeproxy failed to start (exit $($proxy.ExitCode))"
    }

    Write-Host "`n=== edgeproxy demo running (pid $($proxy.Id)) ==="
    Write-Host "  HTTP     http://$listen/"
    if ($Tls) {
        Write-Host "  HTTPS    https://$tlsListen/   (self-signed: curl needs -k)"
    }
    Write-Host "  metrics  http://$metricsListen/metrics"
    Write-Host "  logs     demo/edgeproxy.log, demo/fixture-*.log"
    Write-Host "`nPress Ctrl+C or Enter to stop."
    # Blocks until the operator stops the demo. Ctrl+C also unwinds into the
    # finally block, so either way the children are cleaned up.
    Read-Host | Out-Null
}
finally {
    foreach ($process in $processes) {
        if ($null -ne $process -and -not $process.HasExited) {
            Stop-Process -Id $process.Id -Force
        }
    }
    Pop-Location
}
